const supportedLanguages = ["fr", "en", "es"];
const languageNames = { fr: "Français", en: "English", es: "Español" };
const originalTitle = document.title;
const textNodeTranslations = new WeakMap();
const attributeTranslations = new WeakMap();

function getLanguage() {
  try {
    const savedLanguage = localStorage.getItem("nexora-language");
    return supportedLanguages.includes(savedLanguage) ? savedLanguage : "fr";
  } catch (error) {
    console.error("Unable to read saved language preference:", error);
    return "fr";
  }
}

function translateText(value, language) {
  if (language === "fr") {
    return value;
  }
  return translations[language]?.[value] ?? value;
}

function translatePage(language = getLanguage()) {
  document.documentElement.lang = language;
  document.title = translateText(originalTitle, language);

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (!textNodeTranslations.has(node)) {
      textNodeTranslations.set(node, node.nodeValue);
    }

    const original = textNodeTranslations.get(node);
    const trimmed = original.trim();
    if (trimmed) {
      const normalized = trimmed.replace(/\s+/g, " ");
      const leadingWhitespace = original.match(/^\s*/)?.[0] ?? "";
      const trailingWhitespace = original.match(/\s*$/)?.[0] ?? "";
      node.nodeValue = `${leadingWhitespace}${translateText(normalized, language)}${trailingWhitespace}`;
    }
    node = walker.nextNode();
  }

  for (const element of document.querySelectorAll("[aria-label], [placeholder], [title]")) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      if (!element.hasAttribute(attribute)) {
        continue;
      }
      let originalAttributes = attributeTranslations.get(element);
      if (!originalAttributes) {
        originalAttributes = new Map();
        attributeTranslations.set(element, originalAttributes);
      }
      if (!originalAttributes.has(attribute)) {
        originalAttributes.set(attribute, element.getAttribute(attribute));
      }
      element.setAttribute(
        attribute,
        translateText(originalAttributes.get(attribute), language),
      );
    }
  }

  const description = document.querySelector('meta[name="description"]');
  if (description) {
    const originalDescription = description.dataset.originalContent ?? description.content;
    description.dataset.originalContent = originalDescription;
    description.content = translateText(originalDescription, language);
  }
}

function createLanguageControl() {
  const nav = document.querySelector(".nav");
  if (!nav) {
    return;
  }

  const control = document.createElement("div");
  control.className = "language-control";

  const label = document.createElement("label");
  label.className = "sr-only";
  label.htmlFor = "site-language";
  label.textContent = "Langue / Language / Idioma";

  const select = document.createElement("select");
  select.id = "site-language";
  select.setAttribute("aria-label", label.textContent);
  for (const language of supportedLanguages) {
    const option = document.createElement("option");
    option.value = language;
    option.textContent = languageNames[language];
    select.append(option);
  }

  select.value = getLanguage();
  select.addEventListener("change", () => {
    const language = select.value;
    try {
      localStorage.setItem("nexora-language", language);
    } catch (error) {
      console.error("Unable to save language preference:", error);
    }
    translatePage(language);
    window.dispatchEvent(
      new CustomEvent("nexora-language-change", { detail: { language } }),
    );
  });

  control.append(label, select);
  nav.append(control);
}

window.nexoraLanguage = {
  get: getLanguage,
  text: (value) => translateText(value, getLanguage()),
  translatePage,
};

createLanguageControl();
translatePage();
